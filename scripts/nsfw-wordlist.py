"""Build wordlists/nsfw/nsfw.txt, the NSFW words and phrases the Wordlists page leaves out of the
general lists when its NSFW filter is on.

Usage: python3 scripts/nsfw-wordlist.py KAIKKI

KAIKKI is the English Wiktionary extract from https://kaikki.org/dictionary/English/
(kaikki.org-dictionary-English.jsonl.gz, about 530 MB). Run npm run build afterwards to update the
Wordlists page.

An entry of a general list (one tagged "general") is NSFW if:

- its main sense is tagged vulgar, offensive or a slur on Wiktionary. The main sense is the first
  sense that isn't rare, uncommon, obsolete or archaic, and senses tagged "mildly" vulgar don't
  count. A sense that's a form of other words (an inflection or alternative spelling) is NSFW if
  they all are, so fucked and tits count, and a word with a form sense that isn't NSFW never
  counts, so teeth, balls and cheeks stay (initialisms aren't forms of their expansions); or
- it's a phrase with an NSFW word as one of its words (a phrase is split at spaces and hyphens); or
- it contains one of the worst words below anywhere, such as abso-fucking-lutely; or
- it's in nsfw-wordlist/included.txt,

and it isn't in nsfw-wordlist/excluded.txt, which keeps names like San and Chen.
"""

import gzip
import json
import re
import sys
from pathlib import Path

KAIKKI = sys.argv[1]
HERE = Path(__file__).parent
LISTS = HERE.parent / "wordlists"
OUT = LISTS / "nsfw" / "nsfw.txt"

NSFW_TAGS = {"vulgar", "offensive", "slur"}
UNUSED_TAGS = {"rare", "uncommon", "obsolete", "archaic"}
# the worst words, matched anywhere, but not inside smartwatch, saltwater, swanky, niggardly,
# snigger, twattle, shitake (shiitake), shittim and mishit
WORST = re.compile(
    r"fuck|cunt|(?<!s)nigg(?:a(?!rd)|er|ah|uh|az)|faggot|(?<![st])wank|twat(?!er|ch|tl)|(?<!mi)shit(?!ake|tim|tah|o\b)|motherf",
    re.IGNORECASE,
)


def hand(name):
    return {line.strip() for line in open(HERE / "nsfw-wordlist" / name, encoding="utf-8") if line.strip() and not line.startswith("#")}


INCLUDED, EXCLUDED = hand("included.txt"), hand("excluded.txt")


def read_list(path):
    lines = path.read_text(encoding="utf-8").split("\n")
    if "# tag: general" not in lines[: lines.index("")]:
        return None
    return [line for line in lines if line and not line.startswith("#")]


general = {path.name: words for path in sorted(LISTS.glob("*.txt")) if (words := read_list(path)) is not None}

# word -> [(is NSFW, is unused, [words it's a form of])], over all its entries' senses, in order
senses = {}
with gzip.open(KAIKKI, "rt", encoding="utf-8") as f:
    for line in f:
        e = json.loads(line)
        if e.get("lang_code") != "en":
            continue
        for s in e.get("senses", []):
            tags = set(s.get("tags", []))
            # an initialism's expansion is in alt_of too, but it's not a form of the same word
            if tags & {"abbreviation", "initialism", "acronym"}:
                targets = []
            else:
                targets = [t["word"] for t in s.get("form_of", []) + s.get("alt_of", []) if t.get("word")]
            senses.setdefault(e["word"], []).append(
                (bool(tags & NSFW_TAGS) and "mildly" not in tags, bool(tags & UNUSED_TAGS), targets)
            )


def main_sense_nsfw(word, seen=frozenset()):
    ss = senses.get(word)
    if not ss:
        return False
    seen = seen | {word}
    # form senses pointing back at words already being checked (WTF and wtf) are ignored
    def targets_nsfw(targets):
        targets = [t for t in targets if t not in seen]
        return None if not targets else all(main_sense_nsfw(t, seen) for t in targets)
    if any(targets and targets_nsfw(targets) is False for _, _, targets in ss):
        return False
    flagged, _, targets = next((s for s in ss if not s[1]), ss[0])
    return flagged or bool(targets and targets_nsfw(targets))


words = {w for ws in general.values() for w in ws}
tagged = {w for w in words if main_sense_nsfw(w)}
single = {w for w in tagged if not re.search(r"[ -]", w)}
by_part = {w for w in words if len(parts := re.split(r"[ -]", w)) > 1 and any(p in single for p in parts)}
worst = {w for w in words if WORST.search(w)}
nsfw = (tagged | by_part | worst | (INCLUDED & words)) - EXCLUDED

OUT.parent.mkdir(exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("# NSFW words and phrases left out of the general lists when the Wordlists page's NSFW filter\n")
    f.write("# is on. Generated by scripts/nsfw-wordlist.py: do not edit.\n\n")
    f.write("".join(w + "\n" for w in sorted(nsfw)))

for name, ws in general.items():
    print(f"{name}: {sum(w in nsfw for w in ws)} of {len(ws)}")
print(f"tagged {len(tagged)}, by part {len(by_part - tagged)}, worst {len(worst - tagged - by_part)}, total {len(nsfw)}")
