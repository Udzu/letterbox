// Write sw.js, the service worker that lets the site be installed and used offline.
//
// Usage: node scripts/build-sw.mjs (run by npm run build, after the pages are built)
//
// The service worker keeps a copy of every page, the manifest and the icons (the "app shell"), and
// serves them from that copy, so the site works offline once installed, even pages never visited.
// Each file is listed with a hash of its contents: when a file changes, sw.js changes, so browsers
// install the new service worker, which fetches only the changed files and uses them from the next
// page load. Anything else (the rhymes and word list data, which the pages keep in IndexedDB
// themselves) goes to the network as usual.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const pages = (await readdir(ROOT)).filter((f) => f.endsWith(".html")).sort();
const icons = (await readdir(path.join(ROOT, "icons"))).sort().map((f) => `icons/${f}`);
const files = [...pages, "manifest.json", ...icons];

const hashes = {};
for (const file of files) {
  hashes[file] = createHash("sha256").update(await readFile(path.join(ROOT, file))).digest("hex").slice(0, 12);
}

const worker = `// Generated by scripts/build-sw.mjs: do not edit.
// The app shell: each file and a hash of its contents, kept in the cache under file?v=hash.
const FILES = ${JSON.stringify(hashes, null, 2)};
const CACHE = "letterbox-shell";
const key = (file) => new URL(\`\${file}?v=\${FILES[file]}\`, self.registration.scope).href;

// Install: copy unchanged files from the existing cache and fetch the rest (bypassing the HTTP cache).
self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(Object.keys(FILES).map(async (file) => {
      if (await cache.match(key(file))) return;
      const response = await fetch(new URL(file, self.registration.scope), { cache: "reload" });
      if (!response.ok) throw new Error(\`\${file}: \${response.status}\`);
      await cache.put(key(file), response);
    }));
    await self.skipWaiting();
  })());
});

// Activate: drop cached files that are no longer current, and take over open pages.
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const current = new Set(Object.keys(FILES).map(key));
    for (const request of await cache.keys()) if (!current.has(request.url)) await cache.delete(request);
    await self.clients.claim();
  })());
});

// Fetch: serve app shell files from the cache (the site root as index.html), and leave anything else
// to the network.
self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== "GET" || !url.href.startsWith(self.registration.scope)) return;
  const file = url.pathname.slice(new URL(self.registration.scope).pathname.length) || "index.html";
  if (!(file in FILES)) return;
  event.respondWith((async () => (await caches.match(key(file))) ?? fetch(event.request))());
});
`;
await writeFile(path.join(ROOT, "sw.js"), worker);
console.log(`Wrote sw.js (${files.length} files)`);
